-- Create Tables without Foreign Keys

CREATE TABLE users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255),
    address VARCHAR(255),
    created_at TIMESTAMP,
    role VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (email)
);

CREATE TABLE categories (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    PRIMARY KEY (id),
    UNIQUE (name)
);

CREATE TABLE chat_rooms (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255),
    type VARCHAR(255),
    created_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE medical_facilities (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    phone VARCHAR(255),
    type VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE medicines (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    unit VARCHAR(255),
    description VARCHAR(255),
    is_approved BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    UNIQUE (name)
);

-- Tables with Foreign Keys referencing the above tables

CREATE TABLE ai_chat_sessions (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    title VARCHAR(255),
    created_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_aics_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE block_list (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    blocker_id BIGINT NOT NULL,
    blocked_id BIGINT NOT NULL,
    created_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_bl_blocker FOREIGN KEY (blocker_id) REFERENCES users(id),
    CONSTRAINT fk_bl_blocked FOREIGN KEY (blocked_id) REFERENCES users(id),
    UNIQUE (blocker_id, blocked_id)
);

CREATE TABLE chat_room_members (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    joined_at TIMESTAMP,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    CONSTRAINT fk_crm_room FOREIGN KEY (room_id) REFERENCES chat_rooms(id),
    CONSTRAINT fk_crm_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE health_profiles (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    profile_name VARCHAR(255),
    full_name VARCHAR(255),
    date_of_birth DATE,
    gender VARCHAR(255),
    blood_type VARCHAR(255),
    avatar VARCHAR(255),
    chronic_conditions TEXT,
    emergency_contact_name VARCHAR(255),
    emergency_contact_phone VARCHAR(255),
    user_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_hp_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE messages (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    content TEXT NOT NULL,
    sent_at TIMESTAMP,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    sender_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_msg_sender FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT fk_msg_receiver FOREIGN KEY (receiver_id) REFERENCES users(id),
    CONSTRAINT fk_msg_room FOREIGN KEY (room_id) REFERENCES chat_rooms(id)
);

CREATE TABLE notifications (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    message VARCHAR(255),
    link VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP,
    user_id BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE posts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    media_path VARCHAR(255),
    cloudinary_public_id VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    view_count INTEGER NOT NULL DEFAULT 0,
    like_count INTEGER NOT NULL DEFAULT 0,
    user_id BIGINT NOT NULL,
    category_id BIGINT,
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_post_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_post_cat FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE refresh_tokens (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    token VARCHAR(255) NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_rt_user FOREIGN KEY (user_id) REFERENCES users(id),
    UNIQUE (user_id),
    UNIQUE (token)
);

-- Tables referencing level 2 tables

CREATE TABLE ai_chat_messages (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT,
    role VARCHAR(255),
    content TEXT,
    created_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_aicm_session FOREIGN KEY (session_id) REFERENCES ai_chat_sessions(id)
);

CREATE TABLE allergies (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    allergen_name VARCHAR(255),
    severity VARCHAR(255),
    reaction VARCHAR(255),
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_alg_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE appointments (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    appointment_date DATE,
    doctor_name VARCHAR(255),
    location VARCHAR(255),
    reason TEXT,
    diagnosis TEXT,
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_appt_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE body_metrics (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    height_in_cm DOUBLE PRECISION,
    weight_in_kg DOUBLE PRECISION,
    log_date TIMESTAMP,
    bmi DOUBLE PRECISION,
    systolic_bp INTEGER,
    diastolic_bp INTEGER,
    cholesterol INTEGER,
    glucose INTEGER,
    smoking BOOLEAN DEFAULT FALSE,
    alcohol BOOLEAN DEFAULT FALSE,
    physical_activity BOOLEAN DEFAULT TRUE,
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_bm_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE comments (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    content TEXT NOT NULL,
    created_at TIMESTAMP,
    user_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL,
    parent_id BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_cmt_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_cmt_post FOREIGN KEY (post_id) REFERENCES posts(id),
    CONSTRAINT fk_cmt_parent FOREIGN KEY (parent_id) REFERENCES comments(id)
);

CREATE TABLE documents (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    document_name VARCHAR(255),
    file_path VARCHAR(255),
    upload_date TIMESTAMP,
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_doc_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE insurance_cards (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    card_number VARCHAR(255),
    issue_date DATE,
    expiry_date DATE,
    registration_place VARCHAR(255),
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_ic_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE post_likes (
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    PRIMARY KEY (post_id, user_id),
    CONSTRAINT fk_pl_post FOREIGN KEY (post_id) REFERENCES posts(id),
    CONSTRAINT fk_pl_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE post_reports (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    reporter_id BIGINT,
    post_id BIGINT,
    reason TEXT,
    reported_at TIMESTAMP,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    CONSTRAINT fk_pr_reporter FOREIGN KEY (reporter_id) REFERENCES users(id),
    CONSTRAINT fk_pr_post FOREIGN KEY (post_id) REFERENCES posts(id)
);

CREATE TABLE profile_access (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    access_level VARCHAR(255),
    status VARCHAR(255),
    relationship VARCHAR(255),
    granted_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_pa_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_pa_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

CREATE TABLE saved_posts (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    post_id BIGINT,
    saved_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_sp_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_sp_post FOREIGN KEY (post_id) REFERENCES posts(id)
);

CREATE TABLE vaccinations (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    vaccine_name VARCHAR(255),
    dose_number INTEGER,
    vaccination_date DATE,
    location VARCHAR(255),
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_vac_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id)
);

-- Level 4

CREATE TABLE prescriptions (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    created_date TIMESTAMP,
    doctor_note TEXT,
    appointment_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_presc_appt FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    UNIQUE (appointment_id)
);

-- Level 5

CREATE TABLE prescription_items (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    medicine_id BIGINT NOT NULL,
    prescription_id BIGINT NOT NULL,
    quantity INTEGER,
    dosage VARCHAR(255),
    duration_in_days INTEGER,
    morning_dose VARCHAR(255),
    afternoon_dose VARCHAR(255),
    evening_dose VARCHAR(255),
    noon_dose VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_pi_med FOREIGN KEY (medicine_id) REFERENCES medicines(id),
    CONSTRAINT fk_pi_presc FOREIGN KEY (prescription_id) REFERENCES prescriptions(id)
);

-- Level 6

CREATE TABLE medication_courses (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    medicine_id BIGINT NOT NULL,
    prescription_item_id BIGINT NOT NULL,
    dosage VARCHAR(255),
    frequency VARCHAR(255),
    timing VARCHAR(255),
    notes VARCHAR(255),
    start_date DATE,
    end_date DATE,
    status VARCHAR(255),
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_mc_med FOREIGN KEY (medicine_id) REFERENCES medicines(id),
    CONSTRAINT fk_mc_pi FOREIGN KEY (prescription_item_id) REFERENCES prescription_items(id),
    CONSTRAINT fk_mc_profile FOREIGN KEY (profile_id) REFERENCES health_profiles(id),
    UNIQUE (prescription_item_id)
);

-- Level 7

CREATE TABLE medication_reminders (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    reminder_time TIMESTAMP,
    status VARCHAR(255),
    is_notified BOOLEAN NOT NULL DEFAULT FALSE,
    course_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_mr_course FOREIGN KEY (course_id) REFERENCES medication_courses(id)
);
